-- =====================================================================
-- database/prova_identity_sem_usage.sql  (PO3.1 - RS-8, RS-9, D-N4)
--
-- PROVA: uma role SEM nenhum privilegio na sequencia da identity consegue
-- fazer INSERT sem id (o valor vem da identity), nos modos BY DEFAULT e
-- ALWAYS; em ALWAYS, INSERT com id sem OVERRIDING SYSTEM VALUE falha
-- (428C9). Tambem mostra que, sem INSERT na coluna id (D-N4: a
-- api_mapas_escrita recebe so INSERT (graphy, metry)), informar id e
-- negado (42501) mesmo com OVERRIDING SYSTEM VALUE.
--
-- USO: so em ambiente descartavel (ex.: container postgis/postgis:17-3.5)
-- ou pelo DBA. Tudo roda numa transacao terminada em ROLLBACK: a role
-- e o schema de teste nao sobram. NAO toca em public.mapas.
-- Execucao (superusuario):
--   psql -X -v ON_ERROR_STOP=1 -U <superusuario> -d <base> -f database/prova_identity_sem_usage.sql
-- Resultado esperado: so NOTICE "OK ..." e, no fim, "PROVA CONCLUIDA".
-- Qualquer divergencia vira RAISE EXCEPTION (e ROLLBACK).
-- =====================================================================

\set ON_ERROR_STOP on

BEGIN;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = current_user AND rolsuper) THEN
        RAISE EXCEPTION 'prova: exige superusuario (atual: %)', current_user;
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'prova_identity_sem_usage')
       OR to_regnamespace('prova_identity') IS NOT NULL THEN
        RAISE EXCEPTION 'prova: role prova_identity_sem_usage ou schema prova_identity ja existem; abortado';
    END IF;
END
$$;

CREATE ROLE prova_identity_sem_usage NOLOGIN;
CREATE SCHEMA prova_identity;
-- Mesma forma de public.mapas (int4 identity BY DEFAULT), colunas de texto
-- no lugar das geometrias (a prova e sobre a identity, nao sobre o PostGIS).
CREATE TABLE prova_identity.mapas (
    id     int4 GENERATED BY DEFAULT AS IDENTITY
           (INCREMENT BY 1 MINVALUE 1 MAXVALUE 2147483647 START 1 CACHE 1 NO CYCLE) NOT NULL,
    graphy text NULL,
    metry  text NULL,
    CONSTRAINT mapas_pkey PRIMARY KEY (id)
);
-- Privilegios iguais aos da api_mapas_escrita revisada (D-N4), e NADA na
-- sequencia.
GRANT USAGE ON SCHEMA prova_identity TO prova_identity_sem_usage;
GRANT SELECT (id, graphy, metry) ON prova_identity.mapas TO prova_identity_sem_usage;
GRANT INSERT (graphy, metry)     ON prova_identity.mapas TO prova_identity_sem_usage;
GRANT UPDATE (graphy, metry)     ON prova_identity.mapas TO prova_identity_sem_usage;

DO $$
DECLARE
    v_seq text := pg_get_serial_sequence('prova_identity.mapas', 'id');
BEGIN
    IF has_sequence_privilege('prova_identity_sem_usage', v_seq, 'USAGE')
       OR has_sequence_privilege('prova_identity_sem_usage', v_seq, 'SELECT')
       OR has_sequence_privilege('prova_identity_sem_usage', v_seq, 'UPDATE') THEN
        RAISE EXCEPTION 'prova: a role tem privilegio na sequencia %', v_seq;
    END IF;
    IF has_column_privilege('prova_identity_sem_usage', 'prova_identity.mapas', 'id', 'INSERT') THEN
        RAISE EXCEPTION 'prova: a role tem INSERT em id';
    END IF;
    RAISE NOTICE 'OK 0: sem USAGE/SELECT/UPDATE na sequencia % e sem INSERT em id', v_seq;
END
$$;

-- ---------------------------------------------------------------------
-- 1. Modo BY DEFAULT: INSERT sem id funciona sem USAGE na sequencia
-- ---------------------------------------------------------------------
SET LOCAL ROLE prova_identity_sem_usage;
DO $$
DECLARE
    v_id int4;
BEGIN
    INSERT INTO prova_identity.mapas (graphy) VALUES ('g1') RETURNING id INTO v_id;
    IF v_id IS NULL THEN
        RAISE EXCEPTION 'prova 1: RETURNING id veio NULL';
    END IF;
    RAISE NOTICE 'OK 1: BY DEFAULT, INSERT sem id e sem USAGE gerou id %', v_id;

    -- nextval direto (o que um serial/DEFAULT nextval() faria) e negado.
    BEGIN
        PERFORM nextval(pg_get_serial_sequence('prova_identity.mapas', 'id'));
        RAISE EXCEPTION 'prova 1: nextval direto deveria ser negado';
    EXCEPTION WHEN insufficient_privilege THEN
        RAISE NOTICE 'OK 1b: nextval direto negado (42501), como esperado';
    END;

    -- Informar id sem INSERT na coluna id e negado.
    BEGIN
        INSERT INTO prova_identity.mapas (id, graphy) VALUES (1000, 'g-x');
        RAISE EXCEPTION 'prova 1: INSERT com id deveria ser negado (sem INSERT em id)';
    EXCEPTION WHEN insufficient_privilege THEN
        RAISE NOTICE 'OK 1c: INSERT informando id negado (42501) sem privilegio em id';
    END;
END
$$;
RESET ROLE;

-- ---------------------------------------------------------------------
-- 2. Muda para ALWAYS (como a migracao, passo 8)
-- ---------------------------------------------------------------------
ALTER TABLE prova_identity.mapas ALTER COLUMN id SET GENERATED ALWAYS;
-- Para o passo 3d: a role ganha INSERT em id SO nesta prova, para mostrar
-- que ALWAYS barra o id mesmo com o privilegio de coluna.
GRANT INSERT (id) ON prova_identity.mapas TO prova_identity_sem_usage;

-- ---------------------------------------------------------------------
-- 3. Modo ALWAYS
-- ---------------------------------------------------------------------
SET LOCAL ROLE prova_identity_sem_usage;
DO $$
DECLARE
    v_id int4;
BEGIN
    INSERT INTO prova_identity.mapas (metry) VALUES ('m1') RETURNING id INTO v_id;
    IF v_id IS NULL THEN
        RAISE EXCEPTION 'prova 3: RETURNING id veio NULL';
    END IF;
    RAISE NOTICE 'OK 3a: ALWAYS, INSERT sem id e sem USAGE gerou id %', v_id;

    -- 3b UPDATE pela PK continua (W1/W2)
    UPDATE prova_identity.mapas SET graphy = 'g2' WHERE id = v_id;
    RAISE NOTICE 'OK 3b: UPDATE (graphy) WHERE id = % funcionou', v_id;

    -- 3c ALWAYS: id explicito sem OVERRIDING falha com 428C9
    BEGIN
        INSERT INTO prova_identity.mapas (id, graphy) VALUES (2000, 'g-y');
        RAISE EXCEPTION 'prova 3: INSERT com id em ALWAYS deveria falhar';
    EXCEPTION WHEN generated_always THEN
        RAISE NOTICE 'OK 3c: ALWAYS, INSERT com id sem OVERRIDING SYSTEM VALUE falhou com 428C9';
    END;
END
$$;
RESET ROLE;

-- 3d Sem INSERT em id (a forma final da api_mapas_escrita), nem com
--    OVERRIDING SYSTEM VALUE o id entra.
REVOKE INSERT (id) ON prova_identity.mapas FROM prova_identity_sem_usage;
SET LOCAL ROLE prova_identity_sem_usage;
DO $$
BEGIN
    BEGIN
        INSERT INTO prova_identity.mapas (id, graphy) OVERRIDING SYSTEM VALUE VALUES (3000, 'g-z');
        RAISE EXCEPTION 'prova 3d: OVERRIDING SYSTEM VALUE sem INSERT em id deveria ser negado';
    EXCEPTION WHEN insufficient_privilege THEN
        RAISE NOTICE 'OK 3d: OVERRIDING SYSTEM VALUE sem INSERT em id negado (42501)';
    END;
END
$$;
RESET ROLE;

DO $$
BEGIN
    IF (SELECT count(*) FROM prova_identity.mapas) <> 2 THEN
        RAISE EXCEPTION 'prova: esperado 2 linhas na tabela de prova';
    END IF;
    RAISE NOTICE 'PROVA CONCLUIDA: identity gera id sem USAGE na sequencia (BY DEFAULT e ALWAYS); ALWAYS barra id explicito (428C9); sem INSERT em id, nem OVERRIDING passa (42501).';
END
$$;

ROLLBACK;
